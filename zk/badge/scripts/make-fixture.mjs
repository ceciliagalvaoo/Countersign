// Generates a real proof + attestation and writes them as a Rust test fixture for the BadgeVerifier contract.
// Usage (after build.sh): node scripts/make-fixture.mjs ../../contracts/badge-verifier/contracts/badge-verifier/src/test_fixture.rs
import { readFileSync, writeFileSync } from 'node:fs';
import crypto from 'node:crypto';
import * as snarkjs from 'snarkjs';
import { poseidon2 } from 'poseidon-lite';
import { Keypair } from '@stellar/stellar-sdk';

const out = process.argv[2];
const vk = JSON.parse(readFileSync('keys/vk-soroban.json', 'utf8'));

const fe = (dec) => BigInt(dec).toString(16).padStart(64, '0');
const toProof = (p) => ({
  a: fe(p.pi_a[0]) + fe(p.pi_a[1]),
  b: fe(p.pi_b[0][1]) + fe(p.pi_b[0][0]) + fe(p.pi_b[1][1]) + fe(p.pi_b[1][0]),
  c: fe(p.pi_c[0]) + fe(p.pi_c[1]),
});

// Investor with 1,500.00 USDC invested proves the SILVER tier (>= 1,000.00 USDC)
const TOTAL_CENTS = 150000n;
const THRESHOLD = 100000n;
const salt = BigInt('0x' + crypto.randomBytes(31).toString('hex'));

const commitment = poseidon2([TOTAL_CENTS, salt]);
const { proof, publicSignals } = await snarkjs.groth16.fullProve(
  { totalCents: TOTAL_CENTS.toString(), salt: salt.toString(), commitment: commitment.toString(), threshold: THRESHOLD.toString() },
  'build/investor_tier_js/investor_tier.wasm',
  'build/tier_final.zkey'
);
const commitmentHex = fe(publicSignals[0]);

// Attestation by a deterministic test attester key (seed = 32 x 0x07)
const seed = Buffer.alloc(32, 7);
const pkcs8 = Buffer.concat([Buffer.from('302e020100300506032b657004220420', 'hex'), seed]);
const privateKey = crypto.createPrivateKey({ key: pkcs8, format: 'der', type: 'pkcs8' });
const attesterPub = crypto.createPublicKey(privateKey).export({ format: 'der', type: 'spki' }).subarray(-32);

// Random investor wallet; the Rust test uses the same strkey
const investor = Keypair.random().publicKey();
const message = Buffer.concat([Buffer.from('TSF-BADGE-v1'), Buffer.from(commitmentHex, 'hex'), Buffer.from(investor)]);
const attestation = crypto.sign(null, message, privateKey).toString('hex');

const p = toProof(proof);
const rust = `// Generated by zk/badge/scripts/make-fixture.mjs: a real Groth16 proof from the investor_tier circuit.
pub const VK_ALPHA: &str = "${vk.alpha}";
pub const VK_BETA: &str = "${vk.beta}";
pub const VK_GAMMA: &str = "${vk.gamma}";
pub const VK_DELTA: &str = "${vk.delta}";
pub const VK_IC: [&str; ${vk.ic.length}] = [${vk.ic.map((x) => `"${x}"`).join(', ')}];
pub const PROOF_A: &str = "${p.a}";
pub const PROOF_B: &str = "${p.b}";
pub const PROOF_C: &str = "${p.c}";
pub const COMMITMENT: &str = "${commitmentHex}";
pub const THRESHOLD: u64 = ${THRESHOLD};
pub const TOTAL_CENTS: u64 = ${TOTAL_CENTS};
pub const ATTESTER_PUB: &str = "${attesterPub.toString('hex')}";
pub const INVESTOR: &str = "${investor}";
pub const ATTESTATION: &str = "${attestation}";
`;
writeFileSync(out, rust);
console.log(`Wrote ${out}; snarkjs verify:`, await snarkjs.groth16.verify(JSON.parse(readFileSync('keys/verification_key.json', 'utf8')), publicSignals, proof));
